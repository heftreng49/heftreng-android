// Zazakî ve Soranî için çeviri yoksa Kurmancî'ye düşer
const t = (l: L, tr: string, ku: string, zza?: string, ckb?: string) => {
  if (l === 'ckb') return ckb ?? ku;
  if (l === 'zza') return zza ?? ku;
  if (l === 'ku')  return ku;
  return tr;
};

